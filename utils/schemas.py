class LoanState(TypedDict):
    gender: str | None
    age: int | None
    marital_status: str | None
    employment_status: str | None
    has_child: bool | None

    # Outputs generated by the graph
    loan_amount: int | None
    interest_rate: int | None
    bot_message: str | None
